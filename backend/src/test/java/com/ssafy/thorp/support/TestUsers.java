package com.ssafy.thorp.support;

import org.springframework.jdbc.core.JdbcTemplate;

/**
 * 테스트가 쓰는 요청자 계정을 만든다.
 *
 * <p>요청자 식별자를 상수로 적는 테스트가 여럿 있다({@code OWNER = 7L}). 그 값이 {@code users}에 없어도 지금까지는 통과했다 — {@code
 * param_search.owner_user_id}에는 FK가 없기 때문이다. 내 기록(spec 006)의 {@code my_record.owner_id}는 {@code
 * users(id)} FK라(data-model §1) 접수가 기록을 만들 때 그 요청자가 실제로 있어야 한다.
 *
 * <p>운영에서는 요청자가 세션에서 오므로 없는 사용자가 접수하는 일이 없다. 테스트만 그 전제를 비켜 갔던 것이고, 여기서 계정을 만들어 전제를 맞춘다.
 */
public final class TestUsers {

    private TestUsers() {}

    /**
     * 그 식별자의 계정이 없으면 만든다. {@code users.id}는 {@code GENERATED BY DEFAULT AS IDENTITY}라 값을 직접 넣을 수
     * 있다.
     *
     * @return 넘긴 식별자 그대로. 호출부에서 그대로 쓰라고 돌려준다
     */
    public static long ensure(JdbcTemplate jdbcTemplate, long id) {
        jdbcTemplate.update(
                """
                INSERT INTO users (id, email, password_hash, nickname, phone_number, status,
                    paper_ranking_enabled, live_ranking_enabled, ranking_display_nickname,
                    created_at, updated_at)
                VALUES (?, ?, 'x', ?, ?, 'ACTIVE', false, false, false, NOW(), NOW())
                ON CONFLICT (id) DO NOTHING
                """,
                id,
                "requester" + id + "@t.test",
                "requester" + id,
                "0100000" + String.format("%04d", id));
        // 식별자를 직접 넣으면 IDENTITY 시퀀스가 그대로 남는다. 맞춰 두지 않으면 뒤에 오는 테스트의
        // INSERT 가 같은 값을 다시 받아 중복 키로 죽는다 — 원인이 남의 테스트에 있어 찾기 어렵다.
        jdbcTemplate.queryForObject(
                "SELECT setval(pg_get_serial_sequence('users', 'id'),"
                        + " GREATEST((SELECT COALESCE(MAX(id), 1) FROM users), 1))",
                Long.class);
        return id;
    }
}
