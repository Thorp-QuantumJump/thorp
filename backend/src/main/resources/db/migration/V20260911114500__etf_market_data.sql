-- 001 대표 ETF 자료 확보. 근거: specs/001-etf-market-data/data-model.md, spec.md FR-001·FR-003·FR-013·FR-017,
-- contracts/market-dataset.md, specs/004-backtest-execution/contracts/market-data-input.md.
--
-- 원칙
--  - 열 이름은 001 기준이다: date, dataset_id, adjusted_close, price_carried_forward (2026-09-11 확정).
--  - 불변식은 애플리케이션이 아니라 DB가 강제한다. 적재하는 쪽이 파이썬 파이프라인이고 읽는 쪽이
--    백엔드·워커라 공통 강제 지점이 DB뿐이다.
--  - 발행된 자료 버전과 딸린 시계열은 UPDATE·DELETE를 거부한다 (FR-017). 자료를 고치려면 새 dataset_id다.
--  - 거래정지일은 결측이 아니다. 행을 만들고 trading_suspended = TRUE로 표시한다. 진짜 결측은 행이 없다.
--  - 거래일 달력은 daily_index의 날짜 집합이 맡는다. 별도 거래일 표를 두지 않는다
--    (contracts/market-dataset.md ※1).
--  - 관계형 표의 PK는 GENERATED BY DEFAULT AS IDENTITY다. 쓰기 주체가 파이썬 파이프라인이라
--    시퀀스 nextval을 손으로 부르지 않아도 되고, 필요하면 id를 명시해 넣을 수도 있다.

-- ---------------------------------------------------------------------------
-- 관계형 개체
-- ---------------------------------------------------------------------------

-- 섹터. code가 외부 식별자이고 PK(id)는 노출하지 않는다 (ADR-0002 D2).
CREATE TABLE sector (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(64)  NOT NULL,
    name           VARCHAR(200) NOT NULL,
    classification VARCHAR(16)  NOT NULL,
    description    TEXT,
    CONSTRAINT uk_sector_code UNIQUE (code),
    CONSTRAINT ck_sector_classification
        CHECK (classification IN ('INDUSTRY', 'THEME'))
);

-- 대표 ETF. 국내 상장 비레버리지·비인버스만 허용한다 (FR-001).
-- leveraged·inverse를 컬럼으로 두는 이유는 원천에서 읽은 값을 확인하고 거부한 근거를 남기기 위함이며,
-- 값이 TRUE인 행은 저장 자체를 거부한다 (data-model.md representative_etf 불변식).
CREATE TABLE representative_etf (
    id              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id   VARCHAR(32)  NOT NULL,
    name            VARCHAR(200) NOT NULL,
    listed_on       DATE         NOT NULL,
    delisted_on     DATE,
    benchmark_index VARCHAR(200) NOT NULL,
    manager         VARCHAR(200) NOT NULL,
    leveraged       BOOLEAN      NOT NULL DEFAULT FALSE,
    inverse         BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_representative_etf_instrument_id UNIQUE (instrument_id),
    -- engine_input.py:20의 기존 패턴과 같은 {6자리}.XKRX 형식이다.
    CONSTRAINT ck_representative_etf_instrument_id_format
        CHECK (instrument_id ~ '^[0-9]{6}\.XKRX$'),
    CONSTRAINT ck_representative_etf_delisted_after_listed
        CHECK (delisted_on IS NULL OR delisted_on > listed_on),
    CONSTRAINT ck_representative_etf_not_leveraged CHECK (leveraged = FALSE),
    CONSTRAINT ck_representative_etf_not_inverse CHECK (inverse = FALSE)
);

-- 섹터-ETF 대응표 버전 (FR-003).
CREATE TABLE sector_etf_map_version (
    id             BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version        VARCHAR(64) NOT NULL,
    effective_from TIMESTAMP WITH TIME ZONE NOT NULL,
    effective_to   TIMESTAMP WITH TIME ZONE,
    is_sample      BOOLEAN     NOT NULL,
    published_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_sector_etf_map_version_version UNIQUE (version),
    CONSTRAINT ck_sector_etf_map_version_period
        CHECK (effective_to IS NULL OR effective_to > effective_from)
);

-- "현재 버전은 최대 하나"를 부분 UNIQUE 인덱스로 강제한다.
-- 조건에 맞는 행마다 같은 상수 TRUE를 색인하므로 두 번째 열린 버전이 들어오면 UNIQUE 위반이다.
-- CHECK로는 다른 행을 볼 수 없고 트리거는 동시 INSERT에서 새는데, UNIQUE 인덱스는 둘 다 막는다.
CREATE UNIQUE INDEX uk_sector_etf_map_version_open
    ON sector_etf_map_version ((effective_to IS NULL))
    WHERE effective_to IS NULL;

-- 대응표 항목. 한 버전 안에서 섹터마다 대표 ETF가 정확히 하나다 (FR-001, SC-001).
-- 같은 ETF가 여러 섹터에 붙는 것은 막지 않는다 (data-model.md).
CREATE TABLE sector_etf_map_entry (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map_version_id BIGINT NOT NULL
                       REFERENCES sector_etf_map_version (id) ON DELETE CASCADE,
    sector_id      BIGINT NOT NULL REFERENCES sector (id),
    etf_id         BIGINT NOT NULL REFERENCES representative_etf (id),
    CONSTRAINT uk_sector_etf_map_entry_version_sector UNIQUE (map_version_id, sector_id)
);

CREATE INDEX idx_sector_etf_map_entry_etf ON sector_etf_map_entry (etf_id);

-- 자료 버전 (FR-013, FR-014).
-- COLLECTING 상태는 저장하지 않는다. 수집이 끝나야 행이 생기므로 존재하는 행은 모두 발행된 것이다.
-- source는 004 계약이 요구한 열이다. 004의 cutoff_at은 data_deadline, note는 failure_reason에 대응한다.
CREATE TABLE dataset_version (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id      VARCHAR(64) NOT NULL,
    data_deadline   TIMESTAMP WITH TIME ZONE NOT NULL,
    collected_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    last_success_at TIMESTAMP WITH TIME ZONE NOT NULL,
    complete        BOOLEAN     NOT NULL,
    failure_reason  TEXT,
    is_sample       BOOLEAN     NOT NULL,
    source          VARCHAR(64) NOT NULL,
    map_version_id  BIGINT      NOT NULL REFERENCES sector_etf_map_version (id),
    CONSTRAINT uk_dataset_version_dataset_id UNIQUE (dataset_id),
    -- 부분 갱신은 사유 없이 남길 수 없다 (FR-014).
    CONSTRAINT ck_dataset_version_incomplete_reason
        CHECK (complete OR failure_reason IS NOT NULL)
);

CREATE INDEX idx_dataset_version_map_version ON dataset_version (map_version_id);

-- 원천 대조 기록 (FR-016, FR-017).
CREATE TABLE reconciliation_record (
    id                 BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_version_id BIGINT      NOT NULL REFERENCES dataset_version (id),
    etf_id             BIGINT      NOT NULL REFERENCES representative_etf (id),
    target_date        DATE        NOT NULL,
    sample_reason      VARCHAR(16) NOT NULL,
    field_name         VARCHAR(64) NOT NULL,
    queried_value      TEXT        NOT NULL,
    disclosed_value    TEXT        NOT NULL,
    difference         TEXT,
    cause              VARCHAR(20) NOT NULL,
    resolution         VARCHAR(20) NOT NULL,
    checked_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    -- 표본은 값이 틀어지기 쉬운 날만이다. 평범한 거래일은 넣지 않는다 (FR-016).
    CONSTRAINT ck_reconciliation_record_sample_reason
        CHECK (sample_reason IN ('LISTING', 'DISTRIBUTION', 'SPLIT')),
    -- FR-017의 처리 규칙을 조합으로 고정한다. 이 네 쌍 밖의 조합은 거부한다.
    -- cause와 resolution을 따로 CHECK하면 "원인 불명인데 재발행" 같은 조합이 통과한다.
    CONSTRAINT ck_reconciliation_record_cause_resolution CHECK (
        (cause, resolution) IN (
            ('MATCH', 'NONE'),
            ('PIPELINE_ERROR', 'REPUBLISHED'),
            ('DEFINITION_DIFF', 'RECORDED_ONLY'),
            ('UNKNOWN', 'RANGE_EXCLUDED')
        )
    )
);

CREATE INDEX idx_reconciliation_record_dataset
    ON reconciliation_record (dataset_version_id, etf_id, target_date);

-- ---------------------------------------------------------------------------
-- 시계열 개체
-- ---------------------------------------------------------------------------
-- 모두 dataset_id로 dataset_version을 참조한다. 자료 버전 행을 먼저 만든 뒤 시계열을 적재한다.
-- FK 대상이 dataset_version.dataset_id인 이유: 워커·파이프라인이 다루는 값이 문자열 dataset_id이고,
-- 내부 PK(id)를 밖으로 내보내지 않기 위함이다. UNIQUE 열이라 FK 대상으로 쓸 수 있다.

-- 일별 가격. 원시 OHLC(체결용)와 adjusted_close(신호·성과용)를 같은 행에 나눠 담는다 (FR-004).
CREATE TABLE daily_price (
    dataset_id            VARCHAR(64)    NOT NULL REFERENCES dataset_version (dataset_id),
    instrument_id         VARCHAR(32)    NOT NULL,
    date                  DATE           NOT NULL,
    open                  NUMERIC(18, 4) NOT NULL,
    high                  NUMERIC(18, 4) NOT NULL,
    low                   NUMERIC(18, 4) NOT NULL,
    close                 NUMERIC(18, 4) NOT NULL,
    volume                BIGINT         NOT NULL,
    value                 BIGINT         NOT NULL,
    adjusted_close        NUMERIC(20, 8) NOT NULL,
    adjustment_factor     NUMERIC(20, 12) NOT NULL,
    trading_suspended     BOOLEAN        NOT NULL DEFAULT FALSE,
    price_carried_forward BOOLEAN        NOT NULL DEFAULT FALSE,
    -- 자료 버전이 키에 들어가므로 새 버전을 발행해도 옛 버전 행이 그대로 남는다 (FR-017, SC-004).
    CONSTRAINT pk_daily_price PRIMARY KEY (dataset_id, instrument_id, date),
    CONSTRAINT ck_daily_price_instrument_id_format
        CHECK (instrument_id ~ '^[0-9]{6}\.XKRX$'),
    -- worker/src/worker/market_data.py:33 validate_prices와 같은 조건이다.
    CONSTRAINT ck_daily_price_ohlc_positive
        CHECK (open > 0 AND high > 0 AND low > 0 AND close > 0),
    CONSTRAINT ck_daily_price_ohlc_bounds
        CHECK (high >= GREATEST(open, low, close) AND low <= LEAST(open, high, close)),
    CONSTRAINT ck_daily_price_volume_nonnegative CHECK (volume >= 0 AND value >= 0),
    CONSTRAINT ck_daily_price_adjusted_positive
        CHECK (adjusted_close > 0 AND adjustment_factor > 0),
    -- 거래정지일의 표현을 고정한다 (2026-09-11 확정, contracts/market-dataset.md 「거래정지 처리」).
    -- OHLC 네 값이 모두 직전 종가라 서로 같고, volume·value는 0이며, 직전 종가를 썼으므로
    -- price_carried_forward도 TRUE다. 정지가 아닌데 직전 종가를 쓰는 경우는 막지 않는다
    -- (두 열의 뜻이 다르기 때문이다).
    CONSTRAINT ck_daily_price_suspended_shape CHECK (
        NOT trading_suspended
        OR (open = close AND high = close AND low = close
            AND volume = 0 AND value = 0 AND price_carried_forward)
    )
);

-- 004 계약 「조회 패턴」이 요구한 인덱스. 워커는 한 종목의 한 자료 버전을 기간으로 훑는데,
-- PK 선두가 dataset_id라 그 조회를 효율적으로 처리하지 못한다.
CREATE INDEX idx_daily_price_instrument_dataset_date
    ON daily_price (instrument_id, dataset_id, date);

-- 기업행위. ex_date는 조정 계수 산출에, pay_date는 지급일 현금 반영에 쓴다 (004 계약).
CREATE TABLE corporate_action (
    dataset_id    VARCHAR(64)    NOT NULL REFERENCES dataset_version (dataset_id),
    instrument_id VARCHAR(32)    NOT NULL,
    ex_date       DATE           NOT NULL,
    pay_date      DATE,
    event_type    VARCHAR(16)    NOT NULL,
    amount        NUMERIC(20, 8) NOT NULL,
    CONSTRAINT pk_corporate_action
        PRIMARY KEY (dataset_id, instrument_id, ex_date, event_type),
    CONSTRAINT ck_corporate_action_instrument_id_format
        CHECK (instrument_id ~ '^[0-9]{6}\.XKRX$'),
    CONSTRAINT ck_corporate_action_event_type
        CHECK (event_type IN ('DISTRIBUTION', 'SPLIT')),
    CONSTRAINT ck_corporate_action_amount_positive CHECK (amount > 0),
    -- 분배금은 지급일이 있고 락일 이후이며, 분할은 지급일이 없다 (data-model.md 불변식).
    CONSTRAINT ck_corporate_action_pay_date CHECK (
        (event_type = 'DISTRIBUTION' AND pay_date IS NOT NULL AND pay_date >= ex_date)
        OR (event_type = 'SPLIT' AND pay_date IS NULL)
    )
);

CREATE INDEX idx_corporate_action_instrument_dataset_ex_date
    ON corporate_action (instrument_id, dataset_id, ex_date);

-- 지수 자료. 기업행위도 거래정지도 없으므로 adjusted_close·adjustment_factor·
-- price_carried_forward·trading_suspended를 두지 않는다. 키는 instrument_id가 아니라 index_code다.
-- 이 표의 날짜 집합이 거래일 달력이다 (contracts/market-dataset.md ※1).
CREATE TABLE daily_index (
    dataset_id VARCHAR(64)    NOT NULL REFERENCES dataset_version (dataset_id),
    index_code VARCHAR(32)    NOT NULL,
    date       DATE           NOT NULL,
    open       NUMERIC(18, 4) NOT NULL,
    high       NUMERIC(18, 4) NOT NULL,
    low        NUMERIC(18, 4) NOT NULL,
    close      NUMERIC(18, 4) NOT NULL,
    volume     BIGINT         NOT NULL,
    value      BIGINT         NOT NULL,
    CONSTRAINT pk_daily_index PRIMARY KEY (dataset_id, index_code, date),
    CONSTRAINT ck_daily_index_ohlc_positive
        CHECK (open > 0 AND high > 0 AND low > 0 AND close > 0),
    CONSTRAINT ck_daily_index_ohlc_bounds
        CHECK (high >= GREATEST(open, low, close) AND low <= LEAST(open, high, close)),
    CONSTRAINT ck_daily_index_volume_nonnegative CHECK (volume >= 0 AND value >= 0)
);

CREATE INDEX idx_daily_index_code_dataset_date
    ON daily_index (index_code, dataset_id, date);

-- 자료 부족 구간 (FR-006, FR-017). 공통 평가 기간 산출의 입력이다.
-- SUSPENDED_TOO_LONG은 PD-19·PD-20 확정 뒤에만 쓴다. 값 자체는 미리 허용해 둔다.
CREATE TABLE data_gap (
    dataset_id    VARCHAR(64) NOT NULL REFERENCES dataset_version (dataset_id),
    instrument_id VARCHAR(32) NOT NULL,
    start_date    DATE        NOT NULL,
    end_date      DATE        NOT NULL,
    reason        VARCHAR(32) NOT NULL,
    CONSTRAINT pk_data_gap PRIMARY KEY (dataset_id, instrument_id, start_date, reason),
    CONSTRAINT ck_data_gap_instrument_id_format
        CHECK (instrument_id ~ '^[0-9]{6}\.XKRX$'),
    CONSTRAINT ck_data_gap_range CHECK (end_date >= start_date),
    CONSTRAINT ck_data_gap_reason CHECK (
        reason IN (
            'AMBIGUOUS_PRICE',
            'MISSING_CORPORATE_ACTION',
            'SUSPENDED_TOO_LONG',
            'RECONCILIATION_UNKNOWN',
            'INDEX_HISTORY_SHORT'
        )
    )
);

CREATE INDEX idx_data_gap_instrument_dataset_start
    ON data_gap (instrument_id, dataset_id, start_date);

-- 거래정지 구간. daily_price.trading_suspended = TRUE인 연속 구간을 묶은 파생 표다.
-- 일별 표시가 원본이고 둘이 어긋나면 일별 표시를 기준으로 다시 만든다.
-- PD-19·PD-20 결정이 이 표에서 길이 분포를 집계한다 (T015).
CREATE TABLE suspension_period (
    dataset_id    VARCHAR(64) NOT NULL REFERENCES dataset_version (dataset_id),
    instrument_id VARCHAR(32) NOT NULL,
    start_date    DATE        NOT NULL,
    end_date      DATE        NOT NULL,
    trading_days  INTEGER     NOT NULL,
    CONSTRAINT pk_suspension_period PRIMARY KEY (dataset_id, instrument_id, start_date),
    CONSTRAINT ck_suspension_period_instrument_id_format
        CHECK (instrument_id ~ '^[0-9]{6}\.XKRX$'),
    CONSTRAINT ck_suspension_period_range CHECK (end_date >= start_date),
    CONSTRAINT ck_suspension_period_trading_days CHECK (trading_days >= 1)
);

CREATE INDEX idx_suspension_period_instrument_dataset_start
    ON suspension_period (instrument_id, dataset_id, start_date);

-- ---------------------------------------------------------------------------
-- 자료 버전 불변 규칙 (FR-017)
-- ---------------------------------------------------------------------------
-- 발행된 자료 버전과 딸린 시계열 행은 고치지 않는다. 자료를 고쳐야 하면 새 dataset_id로 새 행을 만든다.
-- 애플리케이션 코드에 맡기지 않는 이유: 쓰기 주체가 파이썬 파이프라인이고 psql 같은 직접 접속도 있어,
-- 어느 한 계층의 규칙으로는 quickstart 시나리오 3의 psql UPDATE를 막지 못한다.
--
-- INSERT는 막지 않는다. 수집이 끝난 뒤 자료 버전 행을 만들고 시계열을 적재하는 것이 정상 경로다.
-- 재적재 거부(이미 발행된 버전에 다시 넣는 시도)는 PK 중복으로 걸리고, 파이프라인 쪽 검사는 T004다.
--
-- SQLSTATE를 23514(check_violation)로 내보내 Spring이 DataIntegrityViolationException으로
-- 옮기게 한다. 기본 P0001은 UncategorizedSQLException이 되어 제약 위반과 다르게 보인다.
CREATE OR REPLACE FUNCTION thorp_reject_published_data_change() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION
        'published dataset rows are immutable: % on %', TG_OP, TG_TABLE_NAME
        USING ERRCODE = '23514',
              HINT = 'publish a new dataset_id instead of modifying a published one (FR-017)';
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION thorp_reject_published_data_change() IS
    '발행된 자료 버전과 시계열의 UPDATE·DELETE·TRUNCATE를 거부한다 (spec 001 FR-017).';

CREATE TRIGGER trg_dataset_version_immutable
    BEFORE UPDATE OR DELETE ON dataset_version
    FOR EACH ROW EXECUTE FUNCTION thorp_reject_published_data_change();
CREATE TRIGGER trg_dataset_version_no_truncate
    BEFORE TRUNCATE ON dataset_version
    FOR EACH STATEMENT EXECUTE FUNCTION thorp_reject_published_data_change();

CREATE TRIGGER trg_daily_price_immutable
    BEFORE UPDATE OR DELETE ON daily_price
    FOR EACH ROW EXECUTE FUNCTION thorp_reject_published_data_change();
CREATE TRIGGER trg_daily_price_no_truncate
    BEFORE TRUNCATE ON daily_price
    FOR EACH STATEMENT EXECUTE FUNCTION thorp_reject_published_data_change();

CREATE TRIGGER trg_corporate_action_immutable
    BEFORE UPDATE OR DELETE ON corporate_action
    FOR EACH ROW EXECUTE FUNCTION thorp_reject_published_data_change();
CREATE TRIGGER trg_corporate_action_no_truncate
    BEFORE TRUNCATE ON corporate_action
    FOR EACH STATEMENT EXECUTE FUNCTION thorp_reject_published_data_change();

CREATE TRIGGER trg_daily_index_immutable
    BEFORE UPDATE OR DELETE ON daily_index
    FOR EACH ROW EXECUTE FUNCTION thorp_reject_published_data_change();
CREATE TRIGGER trg_daily_index_no_truncate
    BEFORE TRUNCATE ON daily_index
    FOR EACH STATEMENT EXECUTE FUNCTION thorp_reject_published_data_change();

CREATE TRIGGER trg_data_gap_immutable
    BEFORE UPDATE OR DELETE ON data_gap
    FOR EACH ROW EXECUTE FUNCTION thorp_reject_published_data_change();
CREATE TRIGGER trg_data_gap_no_truncate
    BEFORE TRUNCATE ON data_gap
    FOR EACH STATEMENT EXECUTE FUNCTION thorp_reject_published_data_change();

CREATE TRIGGER trg_suspension_period_immutable
    BEFORE UPDATE OR DELETE ON suspension_period
    FOR EACH ROW EXECUTE FUNCTION thorp_reject_published_data_change();
CREATE TRIGGER trg_suspension_period_no_truncate
    BEFORE TRUNCATE ON suspension_period
    FOR EACH STATEMENT EXECUTE FUNCTION thorp_reject_published_data_change();
