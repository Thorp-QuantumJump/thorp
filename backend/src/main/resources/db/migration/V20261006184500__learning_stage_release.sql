-- spec 013 배우기 2판(B08): 단계 공개·글 추가 변경 기록, 글의 첫 공개 시각, 용어 넘겨받기
-- (specs/013-learning-pages/data-model.md §3-2·§3-3·§3-7, research R24·R27).
--
-- 이 마이그레이션은 데이터를 지우거나 기존 값을 바꾸지 않는다. 지우는 것은 제약 uq_learning_term_key 하나이고, 같은 자리에
-- 부분 유일 색인 둘을 건다. 기존 행은 transfer_from_article_id가 모두 NULL이고 term_key가 지금 유일 제약으로 이미 유일하므로
-- 새 색인을 어길 수 없다. 제약 이름이 바뀌어 409로 바꾸는 대응(presentation/support/UniqueConstraintViolations)도 함께 바꾼다.

-- 3-7. 변경 기록. 추가만 한다. 단계 공개가 STAGE_RELEASED를, 공개된 단계에 처음 게시되는 글이 ARTICLE_ADDED를 쓴다.
-- 그때의 편수와 제목을 적어 두므로 뒤에 제목을 고치거나 글을 옮겨도 지난 기록이 바뀌지 않는다(R27).
-- actor_user_id에 users FK를 걸지 않는다 — 게시 판의 published_by_user_id와 같은 이유다.
CREATE TABLE learning_release_log (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_key        VARCHAR(100)             NOT NULL,
    kind             VARCHAR(16)              NOT NULL,
    stage_id         BIGINT                   NOT NULL,
    article_id       BIGINT,
    new_count        SMALLINT                 NOT NULL,
    rewritten_count  SMALLINT                 NOT NULL,
    rewritten_titles JSONB                    NOT NULL DEFAULT '[]'::jsonb,
    article_title    VARCHAR(100),
    actor_user_id    BIGINT                   NOT NULL,
    occurred_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_learning_release_log_entry_key UNIQUE (entry_key),
    CONSTRAINT ck_learning_release_log_kind CHECK (kind IN ('STAGE_RELEASED', 'ARTICLE_ADDED')),
    -- 글은 ARTICLE_ADDED일 때만 가리킨다.
    CONSTRAINT ck_learning_release_log_article CHECK ((kind = 'ARTICLE_ADDED') = (article_id IS NOT NULL)),
    CONSTRAINT ck_learning_release_log_counts CHECK (new_count >= 0 AND rewritten_count >= 0),
    CONSTRAINT fk_learning_release_log_stage FOREIGN KEY (stage_id) REFERENCES learning_stage (id),
    CONSTRAINT fk_learning_release_log_article FOREIGN KEY (article_id) REFERENCES learning_article (id)
);

-- 3-2. 공개된 단계에 처음 게시된 시각. 한 번 쓴 뒤 비우지 않는다. 비어 있으면 그 글의 다음 공개가 '처음'이다(R27).
ALTER TABLE learning_article
    ADD COLUMN first_released_at TIMESTAMP WITH TIME ZONE;

-- 3-3. 넘겨받는 중인 용어의 지금 소유 글. 넘기기는 넘겨받는 글의 게시 트랜잭션이 한다(R24).
ALTER TABLE learning_term
    ADD COLUMN transfer_from_article_id BIGINT,
    ADD CONSTRAINT fk_learning_term_transfer_from
        FOREIGN KEY (transfer_from_article_id) REFERENCES learning_article (id),
    -- 자기 글에서 넘겨받을 수 없다.
    ADD CONSTRAINT ck_learning_term_transfer_not_self
        CHECK (transfer_from_article_id IS NULL OR transfer_from_article_id <> article_id),
    DROP CONSTRAINT uq_learning_term_key;

-- 소유 중인 행끼리, 넘겨받는 중인 행끼리 각각 term_key가 유일하다. 같은 용어를 동시에 넘겨받는 글은 하나뿐이다.
CREATE UNIQUE INDEX uq_learning_term_key_owned
    ON learning_term (term_key) WHERE transfer_from_article_id IS NULL;
CREATE UNIQUE INDEX uq_learning_term_key_incoming
    ON learning_term (term_key) WHERE transfer_from_article_id IS NOT NULL;
