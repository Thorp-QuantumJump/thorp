-- 001 대표 상품 정보. 근거: specs/001-etf-market-data/data-model.md 「instrument_profile」,
-- spec.md FR-011·FR-015, contracts/sector-api.md 「GET /sectors/{code}/instrument-profile」.
--
-- 이 표가 왜 여기 있나
--  T003(V20260911114500__etf_market_data.sql)이 data-model.md의 표 12개 중 11개를 만들면서 이 표를
--  빠뜨렸고 어느 작업도 맡고 있지 않았다. 2026-09-13에 T012·T013 묶음에서 만들기로 확정했다
--  (tasks.md T013). 열 구성은 data-model.md 그대로이며 새로 설계하지 않았다.
--
-- 이 표의 성격
--  시계열이 아니라 대표 ETF 하나에 딸린 화면 표시용 묶음이다. 그래서 시계열 5개처럼 문자열
--  dataset_id를 갖지 않고 reconciliation_record와 같이 bigint 외래 키 두 개(etf_id,
--  dataset_version_id)를 갖는다(data-model.md).
--
-- UPDATE·DELETE 거부 트리거를 걸지 않는 이유
--  FR-017이 불변으로 못 박은 대상은 "발행된 자료 버전과 딸린 시계열"이고, T003이 트리거를 건 표도
--  dataset_version과 시계열 5개다. 대조 기록(reconciliation_record)도 같은 이유로 트리거 없이 두었다.
--  재현(SC-004)은 자료 버전마다 한 벌씩 새로 쌓는 아래 UNIQUE가 지킨다 — 같은 (etf_id,
--  dataset_version_id)에 두 번째 행이 들어오지 못하므로, 값을 바꾸려면 새 자료 버전이 필요하다.
--
-- 추적 차이 필드를 두지 않는다
--  기획서 §3.3이 항목으로 들었으나 계산 정의가 확정되지 않아 이번 범위에서 뺐다(PD-21,
--  spec.md Out of Scope). 정의가 확정되면 컬럼을 더하는 방향으로 넓힌다.

CREATE TABLE instrument_profile (
    id                        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etf_id                    BIGINT       NOT NULL REFERENCES representative_etf (id),
    dataset_version_id        BIGINT       NOT NULL REFERENCES dataset_version (id),
    index_methodology_summary TEXT         NOT NULL,
    -- 상위 종목과 비중. {"topHoldings": [{"name": ..., "weight": "0.2431"}]} 모양이며 비중은
    -- 문자열이다. jsonb는 숫자를 정규화해 지수 표기·자리수가 바뀔 수 있다(backend/CLAUDE.md).
    holdings_overlap          JSONB        NOT NULL,
    -- true면 화면은 "당시 구성을 재현했다"고 표현하지 않는다 (FR-015).
    holdings_as_of_current    BOOLEAN      NOT NULL,
    -- 최근 3개월 일평균 거래대금(원). 금액이라 TEXT다 — NUMERIC은 scale을 임의로 정해야 하고
    -- 넘는 값을 조용히 반올림한다(data-model.md 불변식, backend/CLAUDE.md).
    avg_daily_value_3m        TEXT         NOT NULL,
    source_attribution        VARCHAR(200) NOT NULL,
    survivorship_note         TEXT         NOT NULL,
    -- 자료 버전마다 대표 ETF 한 건이다 (data-model.md 불변식).
    CONSTRAINT uk_instrument_profile_etf_dataset UNIQUE (etf_id, dataset_version_id),
    -- 지수 표기·부호·빈 문자열을 막는다. 계약이 금액을 plain 문자열로 규정하므로
    -- (contracts/sector-api.md 「공통 규칙」) 읽는 쪽이 그대로 BigDecimal로 옮길 수 있어야 한다.
    CONSTRAINT ck_instrument_profile_avg_daily_value_plain
        CHECK (avg_daily_value_3m ~ '^[0-9]+(\.[0-9]+)?$'),
    -- 상위 종목 목록이 비어 있으면 "중복이 없다"로 읽힌다. 자료가 없으면 행을 만들지 않는다
    -- (원칙 VI). 개별 비중의 범위와 합은 파이프라인이 본다.
    CONSTRAINT ck_instrument_profile_top_holdings CHECK (
        jsonb_typeof(holdings_overlap -> 'topHoldings') = 'array'
        AND jsonb_array_length(holdings_overlap -> 'topHoldings') > 0
    )
);

-- 조회는 "대표 ETF 하나의 가장 최근 자료 버전"이다. 선두를 etf_id로 두어 그 종목의 행만 훑는다.
CREATE INDEX idx_instrument_profile_etf_dataset
    ON instrument_profile (etf_id, dataset_version_id);

COMMENT ON TABLE instrument_profile IS
    '대표 상품 정보. 자료 버전마다 대표 ETF 한 건이다 (spec 001 FR-015).';
