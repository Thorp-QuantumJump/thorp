CREATE TABLE macro_display_version (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    version_key   VARCHAR(40)  NOT NULL,
    change_reason VARCHAR(200) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT pk_macro_display_version PRIMARY KEY (id),
    CONSTRAINT uk_macro_display_version_key UNIQUE (version_key)
);

CREATE TABLE macro_display_field (
    display_version_id BIGINT       NOT NULL,
    field_id           VARCHAR(32)  NOT NULL,
    display_name       VARCHAR(80)  NOT NULL,
    display_order      INTEGER      NOT NULL,
    description        VARCHAR(400),
    CONSTRAINT pk_macro_display_field PRIMARY KEY (display_version_id, field_id),
    CONSTRAINT fk_macro_display_field_version
        FOREIGN KEY (display_version_id) REFERENCES macro_display_version (id),
    CONSTRAINT uk_macro_display_field_order UNIQUE (display_version_id, display_order),
    CONSTRAINT ck_macro_display_field_id CHECK (field_id IN (
        'production', 'consumption_investment', 'external_trade', 'labor',
        'prices_commodities', 'finance_housing', 'overseas'))
);

CREATE TABLE macro_display_indicator (
    display_version_id BIGINT      NOT NULL,
    indicator_id       VARCHAR(64) NOT NULL,
    display_name       VARCHAR(80) NOT NULL,
    display_order      INTEGER     NOT NULL,
    CONSTRAINT pk_macro_display_indicator PRIMARY KEY (display_version_id, indicator_id),
    CONSTRAINT fk_macro_display_indicator_version
        FOREIGN KEY (display_version_id) REFERENCES macro_display_version (id)
);

-- ---------------------------------------------------------------------------
-- 3. 수집 시도 (T008) — 공개 자료 버전과 별개인 운영 상태다
-- ---------------------------------------------------------------------------

CREATE TABLE macro_collection_attempt (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    attempt_key VARCHAR(64) NOT NULL,
    mode        VARCHAR(16) NOT NULL,
    started_at  TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    status      VARCHAR(16) NOT NULL,
    CONSTRAINT pk_macro_collection_attempt PRIMARY KEY (id),
    CONSTRAINT uk_macro_collection_attempt_key UNIQUE (attempt_key),
    CONSTRAINT ck_macro_collection_attempt_mode CHECK (mode IN ('INITIAL', 'REGULAR')),
    CONSTRAINT ck_macro_collection_attempt_status CHECK (status IN (
        'RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED'))
);

CREATE TABLE macro_collection_item_status (
    attempt_id      BIGINT      NOT NULL,
    indicator_id    VARCHAR(64) NOT NULL,
    source          VARCHAR(16) NOT NULL,
    status          VARCHAR(28) NOT NULL,
    last_success_at TIMESTAMPTZ,
    last_error_at   TIMESTAMPTZ,
    error_class     VARCHAR(80),
    quota_exhausted BOOLEAN     NOT NULL DEFAULT FALSE,
    raw_location    VARCHAR(400),
    CONSTRAINT pk_macro_collection_item_status PRIMARY KEY (attempt_id, indicator_id),
    CONSTRAINT fk_macro_collection_item_attempt
        FOREIGN KEY (attempt_id) REFERENCES macro_collection_attempt (id),
    -- 못 받은 이유를 한 덩어리로 묶지 않는다(FR-011). 키가 아직 없는 것, 활용 승인을
    -- 기다리는 것, 권리 판정을 못 한 것, 조건 자체를 모르는 것은 사람이 할 다음 행동이
    -- 전부 다르다. 하나로 뭉뚱그리면 무엇을 해야 하는지가 응답에서 사라진다.
    CONSTRAINT ck_macro_collection_item_status CHECK (status IN (
        'SUCCEEDED', 'FAILED', 'QUOTA_EXHAUSTED', 'KEY_NOT_ISSUED',
        'APPROVAL_PENDING', 'RIGHTS_PENDING', 'RIGHTS_UNVERIFIED', 'SKIPPED'))
);

-- ---------------------------------------------------------------------------
-- 4. 원본 개정 이력과 관측값 (T009)
-- ---------------------------------------------------------------------------

-- append-only. 같은 응답을 다시 받아도 해시로 걸러내고, 실제 개정만 새 행이 된다(FR-009).
CREATE TABLE macro_raw_revision (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    indicator_id       VARCHAR(64) NOT NULL,
    source             VARCHAR(16) NOT NULL,
    target_month       DATE        NOT NULL,
    raw_value          JSONB,
    raw_unit           VARCHAR(40) NOT NULL,
    released_at        TIMESTAMPTZ,
    received_at        TIMESTAMPTZ NOT NULL,
    source_revision_key VARCHAR(80),
    observed_revision  INTEGER     NOT NULL,
    raw_path           VARCHAR(400) NOT NULL,
    raw_hash           CHAR(64)    NOT NULL,
    CONSTRAINT pk_macro_raw_revision PRIMARY KEY (id),
    CONSTRAINT uk_macro_raw_revision_seq UNIQUE (indicator_id, target_month, observed_revision),
    CONSTRAINT ck_macro_raw_revision_month CHECK (EXTRACT(DAY FROM target_month) = 1),
    CONSTRAINT ck_macro_raw_revision_seq CHECK (observed_revision >= 1)
);

CREATE INDEX ix_macro_raw_revision_hash ON macro_raw_revision (indicator_id, raw_hash);

CREATE TABLE macro_dataset_version (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    version_key                 VARCHAR(40) NOT NULL,
    processing_registry_version_id BIGINT   NOT NULL,
    value_rule_fingerprint      CHAR(64)    NOT NULL,
    status                      VARCHAR(16) NOT NULL,
    complete_indicator_count    INTEGER     NOT NULL,
    is_sample_data              BOOLEAN     NOT NULL DEFAULT FALSE,
    raw_manifest_hash           CHAR(64),
    processed_manifest_hash     CHAR(64),
    published_at                TIMESTAMPTZ,
    created_at                  TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_macro_dataset_version PRIMARY KEY (id),
    CONSTRAINT uk_macro_dataset_version_key UNIQUE (version_key),
    CONSTRAINT fk_macro_dataset_version_registry
        FOREIGN KEY (processing_registry_version_id)
        REFERENCES macro_calculation_registry_version (id),
    CONSTRAINT ck_macro_dataset_version_status CHECK (status IN (
        'COLLECTING', 'NORMALIZING', 'VALIDATING', 'PUBLISHING',
        'PUBLISHED', 'FAILED', 'HELD')),
    -- 공개된 버전은 17개가 다 있어야 한다(FR-011). 진행 중인 버전까지 17을 요구하지는
    -- 않는다 — 그러면 수집 중에는 행을 만들 수조차 없다.
    CONSTRAINT ck_macro_dataset_version_complete CHECK (
        status <> 'PUBLISHED' OR (complete_indicator_count = 17 AND published_at IS NOT NULL))
);

CREATE TABLE macro_observation (
    dataset_version_id BIGINT      NOT NULL,
    indicator_id       VARCHAR(64) NOT NULL,
    target_month       DATE        NOT NULL,
    raw_value          JSONB,
    transformed_value  JSONB,
    released_at        TIMESTAMPTZ,
    received_at        TIMESTAMPTZ NOT NULL,
    break_segment      VARCHAR(40),
    missing_reason     VARCHAR(32),
    CONSTRAINT pk_macro_observation PRIMARY KEY (dataset_version_id, indicator_id, target_month),
    CONSTRAINT fk_macro_observation_dataset
        FOREIGN KEY (dataset_version_id) REFERENCES macro_dataset_version (id),
    CONSTRAINT ck_macro_observation_month CHECK (EXTRACT(DAY FROM target_month) = 1),
    -- 변환값이 없으면 왜 없는지가 반드시 있어야 한다(FR-008, 원칙 VI). 사유 없는 빈칸은
    -- 나중에 결측인지 아직 안 채운 것인지 구분되지 않는다. 반대로 값이 있는데 사유가
    -- 붙어 있으면 둘 중 하나가 거짓이다.
    CONSTRAINT ck_macro_observation_missing CHECK (
        (transformed_value IS NULL) = (missing_reason IS NOT NULL)),
    CONSTRAINT ck_macro_observation_missing_reason CHECK (missing_reason IS NULL OR missing_reason IN (
        'SOURCE_NOT_RELEASED', 'COLLECTION_FAILED', 'BASE_MONTH_MISSING', 'BASE_MONTH_ZERO',
        'BEFORE_SERIES_START', 'MONTH_AVERAGE_INCOMPLETE', 'MONTH_END_NO_TRADING_DAY',
        'BREAK_SEGMENT_EXCLUDED'))
);

-- 변환값 하나가 어떤 원본 행들로 만들어졌는지. 월 기말은 그 달 마지막 거래일 한 행을,
-- 월 평균은 그 달 거래일 전부를, 전년동월 대비는 t 와 t-12 를 가리킨다.
CREATE TABLE macro_observation_lineage (
    dataset_version_id BIGINT      NOT NULL,
    indicator_id       VARCHAR(64) NOT NULL,
    target_month       DATE        NOT NULL,
    raw_revision_id    BIGINT      NOT NULL,
    role               VARCHAR(24) NOT NULL,
    CONSTRAINT pk_macro_observation_lineage
        PRIMARY KEY (dataset_version_id, indicator_id, target_month, raw_revision_id),
    CONSTRAINT fk_macro_lineage_observation
        FOREIGN KEY (dataset_version_id, indicator_id, target_month)
        REFERENCES macro_observation (dataset_version_id, indicator_id, target_month),
    CONSTRAINT fk_macro_lineage_raw
        FOREIGN KEY (raw_revision_id) REFERENCES macro_raw_revision (id),
    CONSTRAINT ck_macro_lineage_role CHECK (role IN (
        'TARGET', 'BASE_MONTH', 'MONTH_END_SAMPLE', 'MONTH_AVERAGE_SAMPLE', 'BREAK_LINK'))
);

-- ---------------------------------------------------------------------------
-- 5. 기준월과 현재 포인터 (T010)
-- ---------------------------------------------------------------------------

CREATE TABLE macro_baseline (
    dataset_version_id  BIGINT      NOT NULL,
    registry_version_id BIGINT      NOT NULL,
    scope_id            VARCHAR(32) NOT NULL,
    reference_month     DATE,
    reference_month_held_back_by JSONB NOT NULL,
    computed_at         TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_macro_baseline PRIMARY KEY (dataset_version_id, registry_version_id, scope_id),
    CONSTRAINT fk_macro_baseline_dataset
        FOREIGN KEY (dataset_version_id) REFERENCES macro_dataset_version (id),
    CONSTRAINT fk_macro_baseline_registry
        FOREIGN KEY (registry_version_id) REFERENCES macro_calculation_registry_version (id),
    -- 7개 분야와 전체 하나. 교집합이 비면 reference_month 만 null 이고 행 자체는 남는다 —
    -- 행이 없으면 "아직 계산 안 함"과 "계산했더니 공통 월이 없음"이 같아 보인다.
    CONSTRAINT ck_macro_baseline_scope CHECK (scope_id IN (
        'production', 'consumption_investment', 'external_trade', 'labor',
        'prices_commodities', 'finance_housing', 'overseas', 'ALL')),
    CONSTRAINT ck_macro_baseline_month CHECK (
        reference_month IS NULL OR EXTRACT(DAY FROM reference_month) = 1)
);

-- 한 행짜리 표. 읽는 쪽은 한 트랜잭션에서 세 버전을 먼저 고정한 뒤 조립한다(FR-023).
CREATE TABLE macro_current_publication (
    singleton_key       CHAR(1)     NOT NULL DEFAULT 'X',
    dataset_version_id  BIGINT,
    registry_version_id BIGINT      NOT NULL,
    display_version_id  BIGINT      NOT NULL,
    switched_at         TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_macro_current_publication PRIMARY KEY (singleton_key),
    CONSTRAINT ck_macro_current_publication_singleton CHECK (singleton_key = 'X'),
    CONSTRAINT fk_macro_current_dataset
        FOREIGN KEY (dataset_version_id) REFERENCES macro_dataset_version (id),
    CONSTRAINT fk_macro_current_registry
        FOREIGN KEY (registry_version_id) REFERENCES macro_calculation_registry_version (id),
    CONSTRAINT fk_macro_current_display
        FOREIGN KEY (display_version_id) REFERENCES macro_display_version (id)
);
