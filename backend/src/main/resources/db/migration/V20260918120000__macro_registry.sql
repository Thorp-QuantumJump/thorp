-- 경제지표 등록·수집(spec 008)이 소유하는 표 열둘.
--
-- 값을 넣는 것은 `data/src/data_pipeline/macro/` 배치뿐이고 Backend 는 읽기만 한다
-- (루트 AGENTS.md "Backend는 계산하지 않는다"). 열 이름·제약이 배치 정의와 어긋나면
-- 적재가 운영에서만 깨진다.
--
-- decimal 은 예외 없이 JSONB 문자열이다(V2__backtest_result.sql 규약) — NUMERIC 은 scale 을
-- 임의로 정해야 하고 그 자릿수를 넘는 값을 조용히 반올림하지만, JSON 은 원천이 준 값과
-- 자릿수를 그대로 보존한다. 지표마다 공표 정밀도가 다르므로 여기서 특히 중요하다.
--
-- 버전이 셋인 이유는 서로 다른 속도로 움직이기 때문이다(FR-003). 화면 문구를 고쳤다고
-- 과거 검색 결과가 달라지면 안 되고, 분야 매핑을 고쳤다고 전 구간을 다시 처리할 이유도 없다.

-- ---------------------------------------------------------------------------
-- 1. 계산 등록표 (T006)
-- ---------------------------------------------------------------------------

CREATE TABLE macro_calculation_registry_version (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    version_key            VARCHAR(40)  NOT NULL,
    value_rule_fingerprint CHAR(64)     NOT NULL,
    change_reason          VARCHAR(200) NOT NULL,
    status                 VARCHAR(16)  NOT NULL,
    created_at             TIMESTAMPTZ  NOT NULL,
    CONSTRAINT pk_macro_calc_registry PRIMARY KEY (id),
    CONSTRAINT uk_macro_calc_registry_key UNIQUE (version_key),
    CONSTRAINT ck_macro_calc_registry_status CHECK (status IN ('DRAFT', 'PUBLISHED'))
);

-- 값 규칙 지문. 원천·항목·단위·변환·개편 연결·결측 규칙이 재료다(research R3).
-- 지문이 같으면 매핑·가중만 다른 등록표라 관측 시계열을 다시 처리하지 않아도 된다.
CREATE INDEX ix_macro_calc_registry_fingerprint
    ON macro_calculation_registry_version (value_rule_fingerprint);

CREATE TABLE macro_indicator_definition (
    registry_version_id       BIGINT       NOT NULL,
    indicator_id              VARCHAR(64)  NOT NULL,
    field_id                  VARCHAR(32)  NOT NULL,
    primary_source            VARCHAR(16)  NOT NULL,
    table_code                VARCHAR(64),
    item_code                 VARCHAR(64),
    raw_unit                  VARCHAR(40)  NOT NULL,
    transformed_unit          VARCHAR(40)  NOT NULL,
    transform_rule            VARCHAR(24)  NOT NULL,
    release_rule              VARCHAR(200),
    break_link_rule           VARCHAR(200),
    missing_rule              VARCHAR(200),
    agency                    VARCHAR(80)  NOT NULL,
    attribution               VARCHAR(200) NOT NULL,
    license_status            VARCHAR(24)  NOT NULL,
    license_review_status     VARCHAR(24)  NOT NULL,
    license_verified_at       TIMESTAMPTZ,
    license_suspended_at      TIMESTAMPTZ,
    license_suspended_reason  VARCHAR(200),
    published_precision       INTEGER,
    minimum_effective_scale   JSONB,
    refresh_months_n          INTEGER      NOT NULL,
    nominal_weight            JSONB        NOT NULL,
    trading_calendar          VARCHAR(40),
    revision_history_available BOOLEAN     NOT NULL,
    CONSTRAINT pk_macro_indicator_definition PRIMARY KEY (registry_version_id, indicator_id),
    CONSTRAINT fk_macro_indicator_definition_registry
        FOREIGN KEY (registry_version_id) REFERENCES macro_calculation_registry_version (id),
    CONSTRAINT ck_macro_indicator_field CHECK (field_id IN (
        'production', 'consumption_investment', 'external_trade', 'labor',
        'prices_commodities', 'finance_housing', 'overseas')),
    CONSTRAINT ck_macro_indicator_source CHECK (primary_source IN (
        'ecos', 'kosis', 'customs', 'oecd')),
    -- FR-001 표의 변환 여섯이다. SC-007 은 "네 변환 유형"이라 적었지만 표에는 전월 대비
    -- 증가율(주택가격)과 계절조정 비율(실업률)이 따로 있다. 둘 다 원천·규칙이 달라 다른
    -- 유형으로 두지 않으면 등록표가 표를 담지 못한다.
    CONSTRAINT ck_macro_indicator_transform CHECK (transform_rule IN (
        'YOY_GROWTH', 'MOM_GROWTH', 'MONTH_END', 'MONTH_AVERAGE',
        'OFFICIAL_AMOUNT', 'SEASONAL_RATE')),
    -- 권리 판정은 셋을 구분한다(data-model §1). 조건 자체를 모르는 UNVERIFIED 만 발행 보류
    -- 대상이고, PENDING_RIGHTS 는 조건은 공개돼 있으나 이 계열이 어느 쪽인지 물을 창구가
    -- 없는 상태다 — 두바이유가 여기다. 둘을 한 상태로 묶으면 쓸 수 있는 지표까지 막힌다.
    CONSTRAINT ck_macro_indicator_license_review CHECK (license_review_status IN (
        'VERIFIED', 'PENDING_RIGHTS', 'UNVERIFIED')),
    CONSTRAINT ck_macro_indicator_license_status CHECK (license_status IN (
        'ALLOWED', 'RESTRICTED', 'SUSPENDED', 'UNKNOWN')),
    -- 중단은 사유와 시점이 함께 남아야 한다(FR-016b). 왜 빠졌는지 없이 지표만 사라지면
    -- 나중에 되돌릴 근거가 없다.
    CONSTRAINT ck_macro_indicator_suspension CHECK (
        (license_status <> 'SUSPENDED')
        OR (license_suspended_at IS NOT NULL AND license_suspended_reason IS NOT NULL)),
    CONSTRAINT ck_macro_indicator_refresh CHECK (refresh_months_n >= 1)
);

-- 지표 하나가 한 분야에만 속하는지는 적재기가 본다(T011·T015). 분야별 개수는 DB 제약으로
-- 표현할 수 없다 — 17개·7분야는 행 단위가 아니라 등록표 단위의 불변식이다.
CREATE INDEX ix_macro_indicator_definition_field
    ON macro_indicator_definition (registry_version_id, field_id);

-- ---------------------------------------------------------------------------
-- 2. 화면 분류 (T007) — 계산 등록표와 별도 버전이다
