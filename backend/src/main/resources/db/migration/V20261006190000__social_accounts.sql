-- spec 014 소셜 로그인(US6·US7). 근거는 specs/014-user-auth/research.md Decision 11.
--
-- 소셜로만 가입한 계정은 비밀번호가 없다. 기존 행은 모두 비밀번호가 있으므로 NOT NULL을 푸는 것만으로
-- 기존 데이터와 이전 버전 코드에 영향이 없다. 이메일·전화번호의 NOT NULL·UNIQUE는 그대로 둔다.
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;

-- 소셜 계정은 제공자와 제공자 사용자 고유 식별자로 구분한다. 제공자 쪽 이메일은 저장하지 않는다 —
-- 계정의 이메일은 users.email 하나뿐이고, 제공자에서 이메일이 바뀌어도 연결은 유지된다.
CREATE TABLE social_accounts (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES users (id),
    provider         VARCHAR(20)  NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL,
    linked_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    -- 소셜 계정 하나는 Thorp 계정 하나에만 연결된다(FR-021).
    CONSTRAINT uk_social_accounts_provider_user UNIQUE (provider, provider_user_id),
    -- 한 계정은 제공자마다 소셜 계정을 하나만 가진다(FR-021).
    CONSTRAINT uk_social_accounts_user_provider UNIQUE (user_id, provider)
);
