-- (specs/013-learning-pages/data-model.md §3-1~§3-6, §13-2·§13-3).
--
-- 적용된 V20260917101000__learning_content.sql은 고치지 않는다(constitution "스키마 변경 규칙").
-- 이 마이그레이션은 테이블·열·행을 더할 뿐 기존 값을 지우거나 바꾸지 않는다. 기존 행에 NOT NULL을 거는
-- stage_id·stage_position과 공개 배치 CHECK는 아래에서 먼저 채운 뒤 건다. 운영 DB에 아홉 글 밖의 글이 있으면
-- stage_id를 채우지 못해 SET NOT NULL이 실패하고, Flyway가 이 파일 전체를 한 트랜잭션으로 되돌린다(research R15).
--
-- 단계의 이름·수준·한 줄 설명과 27편의 제목·배치는 PD-16 출발안이다. 적용된 뒤에는 이 파일을 고치지 않고
-- 관리 화면(글 제목·배치)이나 새 마이그레이션(단계 정의)으로 바꾼다.

-- 3-1. 고정 단계. 정의는 마이그레이션만 바꾸고, 공개 여부·공개일은 '단계 공개'(B08)만 한 번 쓴다.
-- released_by_user_id에 users FK를 걸지 않는다 — 게시 판의 published_by_user_id와 같은 이유다.
CREATE TABLE learning_stage (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_key           VARCHAR(64)              NOT NULL,
    number              SMALLINT                 NOT NULL,
    name                VARCHAR(40)              NOT NULL,
    level_label         VARCHAR(16)              NOT NULL,
    summary             VARCHAR(120)             NOT NULL,
    released_at         TIMESTAMP WITH TIME ZONE,
    released_by_user_id BIGINT,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_learning_stage_key UNIQUE (stage_key),
    CONSTRAINT uq_learning_stage_number UNIQUE (number),
    CONSTRAINT ck_learning_stage_key_format
        CHECK (stage_key ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND char_length(stage_key) BETWEEN 3 AND 64),
    CONSTRAINT ck_learning_stage_number CHECK (number >= 1),
    -- 공개일과 공개한 계정은 함께 있거나 함께 없다.
    CONSTRAINT ck_learning_stage_released
        CHECK ((released_at IS NULL) = (released_by_user_id IS NULL))
);

