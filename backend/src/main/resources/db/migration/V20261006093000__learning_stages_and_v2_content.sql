-- 3-2. 글의 형식·초안 배치·공개 배치·확인 문제. stage_id·stage_position은 기존 행을 채운 뒤 NOT NULL로 바꾼다.
ALTER TABLE learning_article
    ADD COLUMN format                   VARCHAR(4) NOT NULL DEFAULT 'V1',
    ADD COLUMN stage_id                 BIGINT,
    ADD COLUMN stage_position           SMALLINT,
    ADD COLUMN published_stage_id       BIGINT,
    ADD COLUMN published_stage_position SMALLINT,
    ADD COLUMN quiz                     JSONB      NOT NULL DEFAULT '[]'::jsonb,
    ADD COLUMN quiz_seq                 INTEGER    NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_learning_article_format CHECK (format IN ('V1', 'V2')),
    ADD CONSTRAINT ck_learning_article_quiz_seq CHECK (quiz_seq >= 0),
    ADD CONSTRAINT fk_learning_article_stage
        FOREIGN KEY (stage_id) REFERENCES learning_stage (id),
    ADD CONSTRAINT fk_learning_article_published_stage
        FOREIGN KEY (published_stage_id) REFERENCES learning_stage (id);

