-- 모든 글이 배치를 가진 뒤 NOT NULL과 CHECK를 건다. 아홉 글 밖의 글이 있으면 여기서 실패한다(R15).
ALTER TABLE learning_article
    ALTER COLUMN stage_id SET NOT NULL,
    ALTER COLUMN stage_position SET NOT NULL,
    ADD CONSTRAINT ck_learning_article_stage_position CHECK (stage_position BETWEEN 1 AND 99),
    ADD CONSTRAINT ck_learning_article_published_stage_position
        CHECK (published_stage_position IS NULL OR published_stage_position BETWEEN 1 AND 99),
    -- 불변식: 공개 배치는 공개 중인 판과 함께 있거나 함께 없고, 단계와 단계 안 순서도 함께 있거나 함께 없다.
    ADD CONSTRAINT ck_learning_article_published_stage
        CHECK ((published_stage_id IS NULL) = (published_revision_id IS NULL)),
    ADD CONSTRAINT ck_learning_article_published_position
        CHECK ((published_stage_position IS NULL) = (published_stage_id IS NULL));

CREATE INDEX idx_learning_article_stage ON learning_article (stage_id);

