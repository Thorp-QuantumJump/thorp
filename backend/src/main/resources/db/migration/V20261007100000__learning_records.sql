-- (specs/013-learning-pages/data-model.md §11, research R28·R29·R30).
--
-- 새 테이블 넷만 만든다. 기존 테이블과 데이터를 바꾸지 않는다.
-- 모든 user_id는 users(id)를 가리키고 ON DELETE CASCADE다. 사용자 행이 지워지면 기록도 함께 지워진다(R28).
-- 글·단계 외래키는 삭제 규칙을 두지 않는다. 글과 단계를 지우는 경로가 없다(spec Out of Scope).
-- 네 테이블은 JPA 엔티티 없이 JdbcTemplate으로만 쓴다(tasks T178). ddl-auto가 이 구조를 보지 않으므로 LearningMigrationTest가 지킨다.

-- 11-1. 사용자 × 글. 가장 멀리 읽은 위치, 마지막으로 연 시각, 완료, 처음 모든 문제에 답한 시각, 익힘.
CREATE TABLE learning_progress (
    user_id          BIGINT                   NOT NULL,
    article_id       BIGINT                   NOT NULL,
    furthest_percent SMALLINT                 NOT NULL,
    last_opened_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at     TIMESTAMP WITH TIME ZONE,
    all_answered_at  TIMESTAMP WITH TIME ZONE,
    mastered_at      TIMESTAMP WITH TIME ZONE,
    mastered_via     VARCHAR(16),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_learning_progress PRIMARY KEY (user_id, article_id),
    CONSTRAINT ck_learning_progress_percent CHECK (furthest_percent BETWEEN 0 AND 100),
    CONSTRAINT ck_learning_progress_mastered_via CHECK (mastered_via IN ('FIRST_ANSWER', 'RETRY')),
    CONSTRAINT ck_learning_progress_mastered CHECK ((mastered_at IS NULL) = (mastered_via IS NULL)),
    CONSTRAINT fk_learning_progress_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_learning_progress_article FOREIGN KEY (article_id) REFERENCES learning_article (id)
);

-- 11-2. 사용자 × 문제의 첫 답. 추가만 한다(ON CONFLICT DO NOTHING 뒤 있는 행을 읽는다). 다시 풀기의 답은 저장하지 않는다.
CREATE TABLE learning_answer (
    user_id      BIGINT                   NOT NULL,
    article_id   BIGINT                   NOT NULL,
    question_key VARCHAR(8)               NOT NULL,
    choice_key   VARCHAR(8)               NOT NULL,
    correct      BOOLEAN                  NOT NULL,
    answered_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_learning_answer PRIMARY KEY (user_id, article_id, question_key),
    CONSTRAINT fk_learning_answer_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_learning_answer_article FOREIGN KEY (article_id) REFERENCES learning_article (id)
);

-- 11-3. 경험치 장부. 추가만 한다. 같은 일(사용자, 종류, 대상 키)로 한 번이다(FR-028).
-- 글에 딸린 종류는 article_id를, 단계 완주는 stage_id를 갖는다. 정답 몫 상한은 (user_id, article_id)로 합한다(R29).
CREATE TABLE learning_exp_entry (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL,
    kind       VARCHAR(24)              NOT NULL,
    ref_key    VARCHAR(160)             NOT NULL,
    article_id BIGINT,
    stage_id   BIGINT,
    points     SMALLINT                 NOT NULL,
    earned_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_learning_exp_entry_ref UNIQUE (user_id, kind, ref_key),
    CONSTRAINT ck_learning_exp_entry_kind
        CHECK (kind IN ('ARTICLE_COMPLETED', 'ANSWER_CORRECT', 'ALL_CORRECT', 'STAGE_COMPLETED')),
    CONSTRAINT ck_learning_exp_entry_points CHECK (points BETWEEN 1 AND 100),
    CONSTRAINT ck_learning_exp_entry_target
        CHECK ((kind = 'STAGE_COMPLETED') = (stage_id IS NOT NULL)
           AND (kind = 'STAGE_COMPLETED') = (article_id IS NULL)),
    CONSTRAINT fk_learning_exp_entry_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_learning_exp_entry_article FOREIGN KEY (article_id) REFERENCES learning_article (id),
    CONSTRAINT fk_learning_exp_entry_stage FOREIGN KEY (stage_id) REFERENCES learning_stage (id)
);

CREATE INDEX ix_learning_exp_entry_user_article ON learning_exp_entry (user_id, article_id);

-- 11-4. 받은 배지. 추가만 한다. 콘텐츠가 바뀌어도 지우지 않는다(FR-024). badge_key는 BadgeCatalog가 정한다.
