-- 경제환경 검색(spec 010)이 소유하는 표 넷.
--
-- 값을 넣는 것은 `data/scripts/precompute_regime.py` 배치뿐이고 Backend 는 읽기만 한다
-- (계약 macro-indicator-port.md §0.1). 열 이름·제약이 배치의 SQLAlchemy 정의
-- (`data/src/data_pipeline/regime/load.py`)와 어긋나면 적재가 운영에서만 깨진다.
--
-- decimal 은 예외 없이 JSONB 문자열이다(research R4, V2__backtest_result.sql 규약) —
-- NUMERIC 은 scale 을 임의로 정해야 하고 넘는 값을 조용히 반올림한다.

CREATE TABLE regime_search_snapshot (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    snapshot_key      VARCHAR(200) NOT NULL,
    mode              VARCHAR(16)  NOT NULL,
    field_id          VARCHAR(32),
    baseline_month    DATE         NOT NULL,
    revision          INTEGER      NOT NULL,
    content_hash      CHAR(64)     NOT NULL,
    data_version      VARCHAR(40)  NOT NULL,
    registry_version  VARCHAR(40)  NOT NULL,
    model_version     VARCHAR(40)  NOT NULL,
    status            VARCHAR(24)  NOT NULL,
    status_reason     VARCHAR(48),
    scale             JSONB        NOT NULL,
    comparison_months JSONB        NOT NULL,
    ranked_candidates JSONB        NOT NULL,
    candidate_counts  JSONB        NOT NULL,
    data_asof         JSONB        NOT NULL,
    computed_at       TIMESTAMPTZ  NOT NULL,
    created_at        TIMESTAMPTZ  NOT NULL,
    updated_at        TIMESTAMPTZ  NOT NULL,
    CONSTRAINT pk_regime_search_snapshot PRIMARY KEY (id),
    CONSTRAINT uk_regime_snapshot_key UNIQUE (snapshot_key),
    CONSTRAINT ck_regime_snapshot_mode CHECK (mode IN ('FIELD', 'COMPOSITE')),
    -- 종합은 field_id 가 NULL 이고 분야 검색은 반드시 있다. 이 짝이 어긋나면 식별 키의 범위
    -- 자리를 만들 수 없다.
    CONSTRAINT ck_regime_snapshot_scope
        CHECK ((mode = 'COMPOSITE' AND field_id IS NULL)
            OR (mode = 'FIELD' AND field_id IS NOT NULL)),
    CONSTRAINT ck_regime_snapshot_month CHECK (EXTRACT(DAY FROM baseline_month) = 1),
    CONSTRAINT ck_regime_snapshot_revision CHECK (revision >= 1),
    CONSTRAINT ck_regime_snapshot_status
        CHECK (status IN ('NOT_COMPUTABLE', 'NEAREST_ONLY', 'THRESHOLD_APPLIED')),
    CONSTRAINT ck_regime_snapshot_reason
        CHECK (status_reason IS NULL OR status_reason IN (
            'SCALE_WINDOW_TOO_SHORT', 'SCALE_ZERO', 'QUERY_INPUT_MISSING',
            'NO_CANDIDATE', 'THRESHOLD_NOT_CALIBRATED')),
    -- 계산 불가는 사유가 반드시 있다. 없으면 화면이 "왜 못 보여주는지"를 말할 수 없고,
    -- 그 자리는 곧 "결과 없음"과 구분되지 않는다(원칙 VI).
    CONSTRAINT ck_regime_snapshot_reason_required
        CHECK (status <> 'NOT_COMPUTABLE' OR status_reason IS NOT NULL)
);

-- ⚠ field_id 가 NULL 인 종합 행은 일반 UNIQUE 로 묶이지 않는다(PostgreSQL 에서 NULL 은 서로
-- 구별된다). 그래서 범위 표현식(COALESCE)으로 인덱스를 만든다 — 이것이 없으면 종합만 같은
-- revision 이 여러 번 들어가고, 그 상태는 조회에서 "가장 큰 revision"이 흔들리는 모습으로만
-- 드러난다.
CREATE UNIQUE INDEX uk_regime_snapshot_revision
    ON regime_search_snapshot (mode, COALESCE(field_id, 'ALL'), baseline_month, revision);

-- 같은 내용이 두 번 들어가는 것을 스키마로 막는다(SC-002).
CREATE UNIQUE INDEX uk_regime_snapshot_content
    ON regime_search_snapshot (mode, COALESCE(field_id, 'ALL'), baseline_month, content_hash);

-- 화면이 기준월을 바꿔 가며 최신 행을 읽는 경로.
CREATE INDEX idx_regime_snapshot_latest
    ON regime_search_snapshot (mode, COALESCE(field_id, 'ALL'), baseline_month, revision DESC);

-- 임시 대역이 만든 행의 일괄 폐기 경로(data-model §6.1) — data_version LIKE 'FIXTURE-%'.
CREATE INDEX idx_regime_snapshot_data_version
    ON regime_search_snapshot (data_version);

-- 배치가 기록한 기준월. **화면이 고를 수 있는 달**이며 008 을 실시간으로 읽지 않는다(계약 §0.2).
CREATE TABLE regime_baseline_month (
    scope_id         VARCHAR(32)  NOT NULL,
    baseline_month   DATE         NOT NULL,
    earliest_month   DATE         NOT NULL,
    registry_version VARCHAR(40)  NOT NULL,
    data_version     VARCHAR(40)  NOT NULL,
    updated_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT pk_regime_baseline_month PRIMARY KEY (scope_id),
    CONSTRAINT ck_regime_baseline_month_day CHECK (EXTRACT(DAY FROM baseline_month) = 1),
    CONSTRAINT ck_regime_baseline_earliest_day CHECK (EXTRACT(DAY FROM earliest_month) = 1),
    CONSTRAINT ck_regime_baseline_range CHECK (earliest_month <= baseline_month)
);

-- 표시 후보. snapshot 하나에 최대 10 행(spec FR-013)이며 목록·상세가 직접 읽는다.
CREATE TABLE regime_search_case (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    snapshot_id      BIGINT      NOT NULL,
    rank             SMALLINT    NOT NULL,
    end_month        DATE        NOT NULL,
    distance         JSONB       NOT NULL,
    indicator_values JSONB       NOT NULL,
    explanation      JSONB       NOT NULL,
    era_position     JSONB,
    created_at       TIMESTAMPTZ NOT NULL,
    updated_at       TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_regime_search_case PRIMARY KEY (id),
    CONSTRAINT fk_regime_case_snapshot FOREIGN KEY (snapshot_id)
        REFERENCES regime_search_snapshot (id) ON DELETE CASCADE,
    CONSTRAINT uk_regime_case_rank UNIQUE (snapshot_id, rank),
    -- ±6개월 건너뛰기가 같은 달을 두 번 넣지 않음을 스키마로 고정한다.
    CONSTRAINT uk_regime_case_month UNIQUE (snapshot_id, end_month),
    CONSTRAINT ck_regime_case_rank CHECK (rank BETWEEN 1 AND 10),
    CONSTRAINT ck_regime_case_month CHECK (EXTRACT(DAY FROM end_month) = 1)
);

CREATE INDEX idx_regime_case_rank ON regime_search_case (snapshot_id, rank);

-- 로그인 사용자의 검색 기록. **비로그인 검색은 행을 만들지 않는다**(spec FR-032).
-- 사용자 식별자는 이 표에만 있다 — 사전 계산 결과는 여러 사용자가 공유하는 자원이라
-- snapshot·case 에는 사용자를 가리키는 컬럼이 없고 앞으로도 두지 않는다(FR-036, SC-013).
CREATE TABLE regime_search_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    owner_user_id   BIGINT       NOT NULL,
    -- 특정 revision 을 고정한다. 철회(FR-035)로 그 항목이 사라지면 NULL 이 되고,
    -- 아래 snapshot_key 사본으로 **무엇을 봤는지는 남는다**.
    snapshot_id     BIGINT,
    snapshot_key    VARCHAR(200) NOT NULL,
    entry_path      VARCHAR(24)  NOT NULL,
    baseline_origin VARCHAR(16)  NOT NULL,
    viewed_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT pk_regime_search_log PRIMARY KEY (id),
    CONSTRAINT fk_regime_log_snapshot FOREIGN KEY (snapshot_id)
        REFERENCES regime_search_snapshot (id) ON DELETE SET NULL,
    CONSTRAINT ck_regime_log_entry_path
        CHECK (entry_path IN ('MARKET_FLOW', 'STRATEGY_RESULT')),
    CONSTRAINT ck_regime_log_baseline_origin
        CHECK (baseline_origin IN ('T_G', 'T_ALL', 'USER_SPECIFIED'))
);

CREATE INDEX idx_regime_log_owner ON regime_search_log (owner_user_id, viewed_at DESC);
