-- 초기 스키마. Entity 매핑(ddl-auto=validate)과 1:1로 맞춘다.
-- DB는 운영·로컬·테스트 모두 PostgreSQL이므로 PostgreSQL 문법을 그대로 쓴다.

-- 백테스트 Job. BacktestJobJpaEntity + BaseEntity 기준.
-- PK는 SEQUENCE다. persist() 시점에 PK가 나와야 그 값으로 backtest_id를 INSERT 전에 채울 수 있다.
CREATE SEQUENCE backtest_job_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE backtest_job (
    id                      BIGINT          NOT NULL PRIMARY KEY,
    backtest_id             VARCHAR(32)     NOT NULL UNIQUE,
    strategy_id             VARCHAR(64)     NOT NULL,
    strategy_version        VARCHAR(32)     NOT NULL,
    parameters              JSONB           NOT NULL,
    instrument_ids          JSONB           NOT NULL,
    start_date              DATE            NOT NULL,
    end_date                DATE            NOT NULL,
    initial_cash            NUMERIC(19, 2)  NOT NULL,
    position_sizing_type    VARCHAR(32)     NOT NULL,
    max_position_pct        NUMERIC(5, 4),
    benchmark_instrument_id VARCHAR(32),
    random_seed             INTEGER         NOT NULL,
    status                  VARCHAR(20)     NOT NULL,
    created_at              TIMESTAMP       NOT NULL,
    updated_at              TIMESTAMP       NOT NULL
);

-- 회원. UserEntity 기준. 시각 컬럼은 Instant라 타임존을 담는다(Hibernate TIMESTAMP_UTC).
CREATE TABLE users (
    id                       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                    VARCHAR(255) NOT NULL UNIQUE,
    password_hash            VARCHAR(255) NOT NULL,
    nickname                 VARCHAR(100) NOT NULL,
    phone_number             VARCHAR(20)  NOT NULL UNIQUE,
    profile_image_url        TEXT,
    status                   VARCHAR(30)  NOT NULL,
    paper_ranking_enabled    BOOLEAN      NOT NULL,
    live_ranking_enabled     BOOLEAN      NOT NULL,
    ranking_display_nickname BOOLEAN      NOT NULL,
    last_login_at            TIMESTAMP WITH TIME ZONE,
    created_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at               TIMESTAMP WITH TIME ZONE NOT NULL,
    withdrawn_at             TIMESTAMP WITH TIME ZONE
);

-- 이메일 인증 코드. EmailVerificationEntity 기준.
-- 같은 이메일로 여러 건이 쌓이고 최신 1건만 조회하므로(findTopByEmailOrderByCreatedAtDesc)
-- email에는 UNIQUE가 아니라 인덱스를 둔다.
CREATE TABLE email_verifications (
    id                     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                  VARCHAR(255) NOT NULL,
    verification_code_hash VARCHAR(255) NOT NULL,
    expires_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    verified_at            TIMESTAMP WITH TIME ZONE,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_email_verifications_email_created_at
    ON email_verifications (email, created_at DESC);
