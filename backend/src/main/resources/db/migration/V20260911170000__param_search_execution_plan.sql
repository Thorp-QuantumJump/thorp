-- 탐색 묶음의 실행 조건 스냅샷(spec 007 M3). V3에 빠져 있던 값을 채운다.
--
-- V3은 전략·탐색 공간·선정 규칙·참조 버전만 담았고 **공통 평가 구간·금액·비용 조건·대응표 버전·
-- 공통 워밍업**을 담을 곳이 없었다. 이 값들이 없으면 후보를 한 건 발행할 때마다 현재 시각의 설정을
-- 다시 읽게 되고, 며칠에 걸쳐 발행되는 묶음 안에서 후보들이 서로 다른 조건으로 계산된다 —
-- 나란히 놓고 본 숫자가 비교 가능한 값이 아니게 된다(FR-007·FR-012, 원칙 IV).
--
-- 재발행(JobRepublisher)·재시도(FR-024)는 기동 뒤에도 같은 조건을 다시 조립해야 하므로 메모리에
-- 들고 있을 수 없다. 그래서 컬럼이다.
--
-- 표시용 묶음이라 JSONB다(V2 규약). 개별 필터·정렬 대상이 아니고 한 덩이로 함께 읽고 쓴다.
-- 금액은 문자열로 담는다 — NUMERIC 컬럼은 scale을 임의로 정해야 하고 넘는 값을 조용히 반올림한다.
--
-- DEFAULT를 두는 이유: 이미 적용된 환경에 기존 행이 있을 수 있고, NOT NULL을 기본값 없이 붙이면
-- 그 환경에서 마이그레이션이 실패한다. 새 행은 애플리케이션이 항상 채우므로 빈 객체로 남지 않는다.
ALTER TABLE param_search
    ADD COLUMN execution_plan JSONB NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN param_search.execution_plan IS
    '접수 시점에 고정한 실행 조건(구간·금액·비용·대응표·워밍업·기준 전략). 후보와 기준이 모두 이 값으로 조립된다';
