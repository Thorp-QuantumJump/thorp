-- spec 013 배우기: 글·용어 설명 초안, 불변 게시 판, 게시 기록, 게시 용어 색인 (specs/013-learning-pages/data-model.md §3).
--
-- 초기 자리(§8)의 제목·순서·용어 구성은 PD-16 출발안이다. 적용된 뒤에는 이 파일을 고치지 않고
-- 관리 화면이나 새 마이그레이션으로 바꾼다(constitution "스키마 변경 규칙").
-- 본문·예시·용어 문장은 비운 초안으로 둔다(research R9). 원고는 운영자가 관리 화면에서 넣는다.

-- 3-1. 초안 작업본. 글 하나에 한 행.
CREATE TABLE learning_article (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_key           VARCHAR(64)              NOT NULL,
    title                 VARCHAR(100)             NOT NULL,
    question              VARCHAR(200)             NOT NULL,
    reading_order         INTEGER                  NOT NULL,
    body_blocks           JSONB                    NOT NULL DEFAULT '[]'::jsonb,
    example               JSONB,
    sources               JSONB                    NOT NULL DEFAULT '[]'::jsonb,
    status                VARCHAR(16)              NOT NULL,
    published_revision_id BIGINT,
    draft_version         INTEGER                  NOT NULL DEFAULT 0,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_learning_article_key UNIQUE (article_key),
    CONSTRAINT ck_learning_article_key_format
        CHECK (article_key ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND char_length(article_key) BETWEEN 3 AND 64),
    CONSTRAINT ck_learning_article_reading_order CHECK (reading_order BETWEEN 1 AND 999),
    CONSTRAINT ck_learning_article_status CHECK (status IN ('DRAFT', 'PUBLISHED')),
    CONSTRAINT ck_learning_article_draft_version CHECK (draft_version >= 0),
    -- 불변식: 게시 상태와 공개 중인 판은 함께 있거나 함께 없다.
    CONSTRAINT ck_learning_article_published_revision
        CHECK ((status = 'PUBLISHED') = (published_revision_id IS NOT NULL))
);

-- 3-2. 초안 용어 설명. 글 1 : 용어 N, termId는 모든 글에서 유일하다.
CREATE TABLE learning_term (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_key   VARCHAR(64)              NOT NULL,
    article_id BIGINT                   NOT NULL REFERENCES learning_article (id),
    label      VARCHAR(50)              NOT NULL,
    sentence   VARCHAR(300)             NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_learning_term_key UNIQUE (term_key),
    CONSTRAINT ck_learning_term_key_format
        CHECK (term_key ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND char_length(term_key) BETWEEN 2 AND 64)
);

CREATE INDEX idx_learning_term_article ON learning_term (article_id);

-- 3-3. 불변 게시 판. 추가만 하고 고치거나 지우지 않는다(원칙 VIII).
-- published_by_user_id에 users FK를 걸지 않는다 — 사용자 행의 수명(014)과 게시 기록의 수명을 묶지 않는다.
CREATE TABLE learning_article_revision (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id           BIGINT                   NOT NULL REFERENCES learning_article (id),
    revision_no          INTEGER                  NOT NULL,
    snapshot             JSONB                    NOT NULL,
    check_version        VARCHAR(64)              NOT NULL,
    sector_map_version   VARCHAR(128)             NOT NULL,
    published_by_user_id BIGINT                   NOT NULL,
    published_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_learning_article_revision_no UNIQUE (article_id, revision_no),
    CONSTRAINT ck_learning_article_revision_no CHECK (revision_no >= 1)
);

ALTER TABLE learning_article
    ADD CONSTRAINT fk_learning_article_published_revision
        FOREIGN KEY (published_revision_id) REFERENCES learning_article_revision (id);

-- 3-4. 게시·게시 취소 기록. 추가만 한다.
CREATE TABLE learning_publication_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id    BIGINT                   NOT NULL REFERENCES learning_article (id),
    action        VARCHAR(16)              NOT NULL,
    revision_id   BIGINT REFERENCES learning_article_revision (id),
    actor_user_id BIGINT                   NOT NULL,
    occurred_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_learning_publication_event_action CHECK (action IN ('PUBLISH', 'UNPUBLISH'))
);

CREATE INDEX idx_learning_publication_event_article ON learning_publication_event (article_id, id DESC);

-- 3-5. 게시 용어 색인. 게시·게시 취소가 글 상태 변경과 같은 트랜잭션에서 다시 쓴다(SC-003).
CREATE TABLE learning_published_term (
    term_key    VARCHAR(64)  PRIMARY KEY,
    article_id  BIGINT       NOT NULL REFERENCES learning_article (id),
    revision_id BIGINT       NOT NULL REFERENCES learning_article_revision (id),
    label       VARCHAR(50)  NOT NULL,
    sentence    VARCHAR(300) NOT NULL
);

CREATE INDEX idx_learning_published_term_article ON learning_published_term (article_id);

