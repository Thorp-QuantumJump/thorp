package com.ssafy.thorp.sector.infrastructure.persistence;

import com.ssafy.thorp.sector.domain.model.Sector;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * {@code sector} 테이블 매핑. 도메인 모델과는 {@link SectorMapper}로 변환한다.
 *
 * <p>{@code common.persistence.BaseEntity}를 상속하지 않는다. 이 표에는 {@code created_at}·{@code updated_at}이
 * 없다 — 쓰는 주체가 파이썬 파이프라인이라 JPA Auditing이 값을 채울 자리가 아니고, 상속하면 {@code ddl-auto=validate}가 없는 컬럼을 찾다
 * 실패한다.
 *
 * <p>{@code description}은 매핑하지 않는다. {@code GET /sectors} 계약에 없는 값이라 읽을 이유가 없고, 매핑하지 않은 컬럼은
 * validate의 검사 대상이 아니다.
 */
@Entity
@Table(name = "sector")
class SectorJpaEntity {

    /** 마이그레이션이 {@code GENERATED BY DEFAULT AS IDENTITY}다. 외부로 내보내지 않는다(ADR-0002 D2). */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id")
    private Long id;

    @Column(name = "code", nullable = false, unique = true, length = 64)
    private String code;

    @Column(name = "name", nullable = false, length = 200)
    private String name;

    @Enumerated(EnumType.STRING)
    @Column(name = "classification", nullable = false, length = 16)
    private Sector.Classification classification;

    protected SectorJpaEntity() {}

    Long getId() {
        return id;
    }

    String getCode() {
        return code;
    }

    String getName() {
        return name;
    }

    Sector.Classification getClassification() {
        return classification;
    }
}
