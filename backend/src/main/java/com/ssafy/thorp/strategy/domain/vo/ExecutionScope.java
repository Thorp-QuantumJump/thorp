package com.ssafy.thorp.strategy.domain.vo;

/**
 * 전략 또는 파라미터가 의미를 갖는 실행 목적(FR-020, FR-021).
 *
 * <p>정의 형식은 특정 실행 목적에 종속되지 않는다. 같은 전략 정의와 같은 확정 파라미터 값이 과거 데이터 검증과 실시장 운용 양쪽에서 동일하게 해석될 수 있어야 하며,
 * 어느 한쪽에서만 의미가 있는 파라미터는 스스로 그 범위를 밝힌다.
 */
public enum ExecutionScope {
    /** 과거 데이터로 성과를 검증하는 실행. */
    BACKTEST,

    /** 실시장에서 운용하는 실행. */
    LIVE
}
