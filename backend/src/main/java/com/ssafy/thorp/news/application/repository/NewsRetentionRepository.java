package com.ssafy.thorp.news.application.repository;

import java.util.Map;

/**
 * 뉴스 도메인 자료의 일괄 삭제 경계(spec FR-019·SC-007).
 *
 * <p><b>예외로 남기는 표를 두지 않는다.</b> 기사·묶음·연결·매체 등록·매체 허가 이력·수집 상태·규칙 버전이 모두 대상이다. 감사 목적으로 한 표만 남겨 두면 그
 * 표에 매체명과 주소가 남고, 보관 기한을 지켰다고 말할 수 없게 된다.
 *
 * <p>삭제 실행 결과는 지표와 로그로만 남긴다. 무엇을 지웠는지 적어 두는 장기 감사 표를 새로 만들면 지우려던 자료의 그림자가 그 표에 남는다.
 */
public interface NewsRetentionRepository {

    /**
     * 뉴스 도메인 표를 전부 비운다.
     *
     * <p><b>같은 결과를 두 번 실행해도 안전하다.</b> 이미 비어 있으면 0건을 지우고 조용히 끝난다 — 실패로 보지 않는다. 삭제 작업은 날마다 돌고, 보관 기한이
     * 지난 뒤에는 첫 회차를 뺀 모든 회차가 0건이다.
     *
     * @return 표 이름 → 지운 행 수. 넣은 순서를 지킨다.
     */
    Map<String, Long> purgeAll();
}
